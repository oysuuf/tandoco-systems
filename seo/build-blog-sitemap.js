#!/usr/bin/env node
/* ─────────────────────────────────────────────────────────────────────
   scripts/build-blog-sitemap.js

   Generates /sitemap-blog.xml from the LIVE `blogs` Firestore collection,
   so the blog half of the sitemap never falls behind the actual posts.

   Why a separate blog sitemap (not the main sitemap.xml)?
     - The main sitemap.xml is hand-curated (custom priorities + lastmods
       per marketing page). A generator that rewrote it risks clobbering
       that. A dedicated blog sitemap lets the generator own ONE file
       wholesale and leaves the curated one untouched. robots.txt already
       lists multiple sitemaps (image, shop), so this just adds one more.

   What it does:
     - Reads every blog doc where status == 'published'.
     - Emits <url> entries for https://tandoco.com/blog/<slug>, with
       <lastmod> from updatedAt (fallback publishedAt), changefreq weekly,
       priority 0.6. Sorted by slug for stable, minimal git diffs.
     - Writes sitemap-blog.xml at the repo root.

   GOING FORWARD (never falls behind):
     - This is exported as buildBlogSitemap(), so every blog SEED script
       can call it at the end of its run() — e.g.:
           const { buildBlogSitemap } = require('./build-blog-sitemap');
           await buildBlogSitemap();
       Then the refreshed sitemap-blog.xml lands in the SAME PR as the new
       posts, and a hosting deploy ships it. No Cloud Function needed
       (us-central1 function-deploy quota is exhausted), and nothing to
       remember by hand.
     - It can also be run standalone any time:
           node scripts/build-blog-sitemap.js

   Idempotent: re-running with no post changes produces an identical file.
   ──────────────────────────────────────────────────────────────────── */

const fs = require('fs');
const path = require('path');
const admin = require('firebase-admin');

const SITE = 'https://tandoco.com';
const OUT = path.join(__dirname, '..', 'sitemap-blog.xml');

// YYYY-MM-DD to match the existing sitemap.xml lastmod format.
function ymd(ts) {
  let d;
  if (!ts) d = new Date();
  else if (typeof ts.toDate === 'function') d = ts.toDate();      // Firestore Timestamp
  else if (ts._seconds != null) d = new Date(ts._seconds * 1000); // raw {_seconds}
  else d = new Date(ts);
  if (isNaN(d.getTime())) d = new Date();
  return d.toISOString().slice(0, 10);
}

function xmlEsc(s) {
  return String(s == null ? '' : s).replace(/[&<>"']/g, c =>
    ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&apos;' }[c]));
}

async function buildBlogSitemap() {
  // Reuse an already-initialized app (e.g. when called from a seed script);
  // otherwise initialize against the tandoco project via ADC.
  if (!admin.apps.length) admin.initializeApp({ projectId: 'tandoco' });
  const db = admin.firestore();

  const snap = await db.collection('blogs').where('status', '==', 'published').get();

  const stripTags = s => String(s == null ? '' : s).replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();

  const rows = [];
  snap.forEach(doc => {
    const d = doc.data() || {};
    const slug = (d.slug || '').trim();
    if (!slug) return;
    rows.push({
      slug,
      lastmod: ymd(d.updatedAt || d.publishedAt),
      // Image-sitemap fields: surface each post's hero photo to Google
      // Images, with the post title as the image title + excerpt as caption.
      image: (d.imageUrl || d.coverImageUrl || d.thumbnailUrl || '').trim(),
      title: stripTags(d.title),
      caption: stripTags(d.excerpt || d.seoDescription).slice(0, 200),
    });
  });

  rows.sort((a, b) => a.slug.localeCompare(b.slug));

  const body = rows.map(r => {
    const img = r.image
      ? `\n    <image:image>\n` +
        `      <image:loc>${xmlEsc(r.image)}</image:loc>\n` +
        (r.title ? `      <image:title>${xmlEsc(r.title)}</image:title>\n` : '') +
        (r.caption ? `      <image:caption>${xmlEsc(r.caption)}</image:caption>\n` : '') +
        `    </image:image>`
      : '';
    return (
      `  <url>\n` +
      `    <loc>${SITE}/blog/${xmlEsc(r.slug)}</loc>\n` +
      `    <lastmod>${r.lastmod}</lastmod>\n` +
      `    <changefreq>weekly</changefreq>\n` +
      `    <priority>0.6</priority>${img}\n` +
      `  </url>`
    );
  }).join('\n');

  const withImg = rows.filter(r => r.image).length;
  const xml =
    `<?xml version="1.0" encoding="UTF-8"?>\n` +
    `<!-- AUTO-GENERATED by scripts/build-blog-sitemap.js from the live blogs collection. Do not edit by hand. -->\n` +
    `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap-0.9"\n` +
    `        xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">\n` +
    body + (body ? '\n' : '') +
    `</urlset>\n`;

  fs.writeFileSync(OUT, xml, 'utf8');
  console.log(`[sitemap] wrote ${path.basename(OUT)} with ${rows.length} blog url(s), ${withImg} with images.`);
  return rows.length;
}

module.exports = { buildBlogSitemap };

// Run standalone.
if (require.main === module) {
  buildBlogSitemap().catch(err => { console.error(err); process.exit(1); });
}
